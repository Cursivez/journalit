import fs from 'fs';
import { createHash } from 'crypto';
import {
  assertGeneratedFresh,
  compressJson,
  hashSourceFiles,
  sourceHashHeader,
} from './lib/compressedPayload.mjs';

const localeCodes = [
  'en',
  'es',
  'de',
  'fr',
  'vi',
  'hi',
  'pt-BR',
  'zh',
  'zh-TW',
  'ja',
  'ko',
  'ru',
  'it',
  'ta',
  'ar',
];

function readLocaleObjectLiteral(localeCode) {
  const source = fs.readFileSync(`src/lang/locale/${localeCode}.ts`, 'utf8');
  const match = source.match(
    /const\s+\w+\s*(?::\s*(?:Partial<)?Lang>?)?\s*=\s*([\s\S]*?);\s*(?:\n\s*export\s+type\s+[^;]+;)*\s*\n\s*export\s+default\s+\w+\s*;/
  );
  if (!match) {
    throw new Error(`Unable to extract locale object from ${localeCode}`);
  }
  return match[1];
}

function loadLocale(localeCode) {
  return Function(
    `"use strict"; return (${readLocaleObjectLiteral(localeCode)});`
  )();
}

function hashKeys(keys) {
  return createHash('sha256')
    .update(keys.join('\n'))
    .digest('hex')
    .slice(0, 16);
}

const sourceHash = hashSourceFiles(
  localeCodes
    .map((localeCode) => `src/lang/locale/${localeCode}.ts`)
    .concat([
      'scripts/generate-compressed-locales.mjs',
      'scripts/lib/compressedPayload.mjs',
    ])
);

const outputPath = 'src/lang/compressedLocales.generated.ts';
const sourceHashComment = sourceHashHeader(sourceHash);


if (process.argv.includes('--check')) {
  assertGeneratedFresh(
    outputPath,
    sourceHash,
    'pnpm run i18n:generate-compressed'
  );
} else {
  const locales = Object.fromEntries(
    localeCodes.map((localeCode) => [localeCode, loadLocale(localeCode)])
  );
  const englishLocale = locales.en;
  const englishKeys = Object.keys(englishLocale);
  const keyHash = hashKeys(englishKeys);
  const localePacks = {};
  for (const localeCode of localeCodes) {
    if (localeCode === 'en') {
      continue;
    }

    const locale = locales[localeCode];
    const values = englishKeys.map((key) => {
      const hasTranslation = Object.prototype.hasOwnProperty.call(locale, key);
      if (!hasTranslation) {
        return null;
      }

      return locale[key] === englishLocale[key] ? 0 : locale[key];
    });
    localePacks[localeCode] = await compressJson(values);
  }

  const localeEntries = Object.entries(localePacks)
    .map(
      ([localeCode, data]) =>
        `  '${localeCode}': { format: 'values', data: '${data}' },`
    )
    .join('\n');

  const metadataEntries = Object.entries(locales)
    .map(([localeCode, locale]) => {
      const translatedKeyCount = Object.keys(locale).length;
      const completeness = translatedKeyCount / englishKeys.length;
      return `    '${localeCode}': { translatedKeyCount: ${translatedKeyCount}, completeness: ${completeness.toFixed(4)} },`;
    })
    .join('\n');

  const englishPack = await compressJson(englishLocale);
  const output = `/**\n * Generated by scripts/generate-compressed-locales.mjs.\n${sourceHashComment}\n * Do not edit manually.\n */\nexport const englishPack = '${englishPack}';\n\nexport const localePacks = {\n${localeEntries}\n} as const;\n\nexport const localeBuildInfo = {\n  schemaVersion: 3,\n  keyHash: '${keyHash}',\n  keyCount: ${englishKeys.length},\n  locales: {\n${metadataEntries}\n  },\n} as const;\n`;

  fs.writeFileSync(outputPath, output);
}
